//! Counts written forms over the pinned corpus shards into the committed frequency table.
//!
//! Each source is a directory of parquet files under the corpus root (layout and revisions in
//! `WORKSPACE.md`). A form is a run of word characters, split at `camelCase` and `snake_case` seams and
//! case-folded; only forms spelled with letters alone are kept. Counts are pooled across sources,
//! which weights each source by its scanned volume. The 250,000 commonest forms are kept and each
//! is recorded as its half-octave above the rarest kept one: an order for ranking, stable across
//! corpus revisions.
//!
//! The per-source counts are also written to `local/cache/counts.json` for `tools/corpus.py`.

use std::collections::{BTreeMap, HashMap};
use std::fmt::Write as _;
use std::fs::{self, File};
use std::path::{Path, PathBuf};
use std::thread;

use arrow_array::Array;
use arrow_array::cast::AsArray;
use parquet::arrow::ProjectionMask;
use parquet::arrow::arrow_reader::ParquetRecordBatchReaderBuilder;

use crate::Result;

/// The sources pooled, each a subdirectory of the corpus root with a `text` column.
pub(crate) const SOURCES: [&str; 4] = ["hplt", "hq", "gazette", "gutenberg"];

/// Forms kept in the table.
const KEEP: usize = 250_000;

/// Forms kept per source in `counts.json`.
const KEEP_PER_SOURCE: usize = 800_000;

/// Types a source holds before its tail is cut back to [`PRUNE_TO`], which bounds memory. The cut
/// is far below any kept form.
const PRUNE_AT: usize = 8_000_000;

/// Types left after a prune.
const PRUNE_TO: usize = 3_000_000;

/// Where the table is written.
const OUT: &str = "crates/picur-morph-lexicon/data/frequency.ron";

/// Where the per-source counts are written.
const COUNTS: &str = "local/cache/counts.json";

type Counts = HashMap<Box<str>, u64>;

/// Counts every source, writes the per-source counts and the pooled table.
#[expect(clippy::print_stdout, reason = "CLI report")]
pub(crate) fn convert(root: &Path) -> Result {
    let mut scanned = BTreeMap::new();
    let mut per_source = BTreeMap::new();
    for source in SOURCES {
        let files = parquet_files(&root.join(source))?;
        if files.is_empty() {
            return Err(format!("no parquet files under {}", root.join(source).display()).into());
        }
        let (counts, chars) = count_source(&files)?;
        println!(
            "{source}: {} files, {chars} chars, {} types",
            files.len(),
            counts.len()
        );
        scanned.insert(source, chars);
        per_source.insert(source, top(counts, KEEP_PER_SOURCE));
    }

    write_counts(&scanned, &per_source)?;

    let mut pooled: HashMap<&str, u64> = HashMap::new();
    for rows in per_source.values() {
        for (form, n) in rows {
            if form.chars().all(char::is_alphabetic) {
                *pooled.entry(form).or_default() += n;
            }
        }
    }
    let mut ranked: Vec<(&str, u64)> = pooled.into_iter().collect();
    ranked.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(b.0)));
    ranked.truncate(KEEP);
    let floor = ranked.last().map_or(1, |&(_, n)| n);

    let mut rows: Vec<(&str, u8)> = ranked
        .into_iter()
        .map(|(w, n)| (w, bucket(n, floor)))
        .collect();
    rows.sort_unstable();

    let mut ron = String::from("// Generated by `cargo xtask frequency`. Do not edit.\n[\n");
    for (word, bucket) in &rows {
        writeln!(ron, "    ({word:?},{bucket}),")?;
    }
    ron.push_str("]\n");
    fs::write(OUT, ron)?;
    println!("wrote {} forms to {OUT}", rows.len());
    Ok(())
}

/// The parquet files under `dir`, sorted, so the scan order and any prune are deterministic.
fn parquet_files(dir: &Path) -> Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        for entry in fs::read_dir(&d).map_err(|e| format!("{}: {e}", d.display()))? {
            let path = entry?.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|e| e == "parquet") {
                out.push(path);
            }
        }
    }
    out.sort();
    Ok(out)
}

/// Counts one source: files in parallel, merged in file order.
#[expect(clippy::iter_over_hash_type, reason = "summing is order-independent")]
fn count_source(files: &[PathBuf]) -> Result<(Counts, u64)> {
    let workers = thread::available_parallelism().map_or(4, |n| n.get().min(12));
    let mut total = Counts::new();
    let mut chars = 0;
    for chunk in files.chunks(workers) {
        let parts: Vec<std::result::Result<(Counts, u64), String>> = thread::scope(|s| {
            let handles: Vec<_> = chunk
                .iter()
                .map(|f| s.spawn(move || count_file(f).map_err(|e| e.to_string())))
                .collect();
            handles
                .into_iter()
                .map(|h| {
                    h.join()
                        .unwrap_or_else(|_| Err("counting thread panicked".into()))
                })
                .collect()
        });
        for part in parts {
            let (counts, c) = part?;
            chars += c;
            for (form, n) in counts {
                *total.entry(form).or_default() += n;
            }
            if total.len() > PRUNE_AT {
                total = top(total, PRUNE_TO).into_iter().collect();
            }
        }
    }
    Ok((total, chars))
}

/// Counts the forms of one file's `text` column and the characters scanned.
fn count_file(path: &Path) -> Result<(Counts, u64)> {
    let builder = ParquetRecordBatchReaderBuilder::try_new(File::open(path)?)?;
    let column = builder
        .schema()
        .index_of("text")
        .map_err(|_| format!("{}: no `text` column", path.display()))?;
    let mask = ProjectionMask::roots(builder.parquet_schema(), [column]);
    let reader = builder.with_projection(mask).build()?;

    let mut counts = Counts::new();
    let mut chars = 0;
    let mut add = |text: &str| {
        chars += text.chars().count() as u64;
        forms(text, |form| match counts.get_mut(form) {
            Some(n) => *n += 1,
            None => {
                counts.insert(form.into(), 1);
            }
        });
    };
    for batch in reader {
        let batch = batch?;
        let array = batch.column(0);
        if let Some(a) = array.as_string_opt::<i32>() {
            a.iter().flatten().for_each(&mut add);
        } else if let Some(a) = array.as_string_opt::<i64>() {
            a.iter().flatten().for_each(&mut add);
        } else if let Some(a) = array.as_string_view_opt() {
            a.iter().flatten().for_each(&mut add);
        } else {
            return Err(format!("{}: `text` is {}", path.display(), array.data_type()).into());
        }
    }
    Ok((counts, chars))
}

/// Calls `f` with every case-folded form in `text`.
fn forms(text: &str, mut f: impl FnMut(&str)) {
    let mut folded = String::new();
    for run in text.split(|c: char| !(c.is_alphanumeric() || c == '_')) {
        for part in identifier_parts(run) {
            folded.clear();
            folded.extend(part.chars().flat_map(char::to_lowercase));
            f(&folded);
        }
    }
}

/// A `camelCase` or `snake_case` identifier as its parts, any other word whole.
///
/// Hungarian never writes a capital inside a word, so such a seam is an identifier boundary and
/// `MostSzamlazz` counts as `most` and `szamlazz`.
fn identifier_parts(word: &str) -> impl Iterator<Item = &str> {
    let chars: Vec<(usize, char)> = word.char_indices().collect();
    let mut cuts = vec![0];
    for i in 1..chars.len() {
        let (at, current) = chars[i];
        let previous = chars[i - 1].1;
        let following = chars.get(i + 1).map(|&(_, c)| c);
        if current == '_'
            || previous == '_'
            || ((previous.is_lowercase() || previous.is_numeric()) && current.is_uppercase())
            || (previous.is_uppercase()
                && current.is_uppercase()
                && following.is_some_and(char::is_lowercase))
        {
            cuts.push(at);
        }
    }
    cuts.push(word.len());
    cuts.dedup();
    let parts: Vec<&str> = cuts
        .windows(2)
        .map(|w| word[w[0]..w[1]].trim_matches('_'))
        .collect();
    parts.into_iter().filter(|p| !p.is_empty())
}

/// The `n` commonest forms, ties broken by spelling.
fn top(counts: Counts, n: usize) -> Vec<(Box<str>, u64)> {
    let mut rows: Vec<(Box<str>, u64)> = counts.into_iter().collect();
    rows.sort_unstable_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    rows.truncate(n);
    rows
}

/// Writes the per-source counts as `{"scanned": {source: chars}, "words": {source: {form: n}}}`.
fn write_counts(
    scanned: &BTreeMap<&str, u64>,
    per_source: &BTreeMap<&str, Vec<(Box<str>, u64)>>,
) -> Result {
    let words: BTreeMap<&str, BTreeMap<&str, u64>> = per_source
        .iter()
        .map(|(s, rows)| (*s, rows.iter().map(|(f, n)| (&**f, *n)).collect()))
        .collect();
    let json = serde_json::json!({ "scanned": scanned, "words": words });
    if let Some(dir) = Path::new(COUNTS).parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(COUNTS, serde_json::to_string(&json)?)?;
    Ok(())
}

/// Half-octaves of `n` above the rarest kept count.
#[expect(
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss,
    clippy::cast_precision_loss,
    reason = "a log ratio clamped to the u8 range"
)]
fn bucket(n: u64, floor: u64) -> u8 {
    ((n as f64 / floor as f64).log2() * 2.0)
        .floor()
        .clamp(0.0, 255.0) as u8
}

#[cfg(test)]
mod tests {
    use super::*;

    fn collect(text: &str) -> Vec<String> {
        let mut out = Vec::new();
        forms(text, |f| out.push(f.to_owned()));
        out
    }

    #[test]
    fn forms_fold_case_and_split_identifiers() {
        assert_eq!(
            collect("A Ház, MostSzamlazz snake_case"),
            ["a", "ház", "most", "szamlazz", "snake", "case"]
        );
        assert_eq!(
            collect("NAGYBETŰS Nyomtatvanykitolto"),
            ["nagybetűs", "nyomtatvanykitolto"]
        );
    }
}
