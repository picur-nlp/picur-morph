//! Diacritic restoration, for a word and for a whole text (`REP-DIAC`).

use std::sync::LazyLock;

use picur_morph_lexicon::{Role, frequency, lexicon};

use crate::tables::char_strs;

/// Each bare vowel with the letters an accent could make of it (`REP-DIAC-001`).
static DIACRITICS: LazyLock<Vec<(char, &'static str)>> = LazyLock::new(|| char_strs("Diacritic"));
use picur_morph_ortho::case::{capitalise, lower, lower_initial, starts_upper, upper};
use picur_morph_spell::{Status, check};

use crate::is_all_caps;
use crate::word::is_guarded;
use picur_morph_ortho::{letters, tokens};

/// The Hungarian accented letters, in both cases.
pub(crate) const ACCENTED: &str = "áéíóöőúüűÁÉÍÓÖŐÚÜŰ";

/// Most vowels a token may have before restoration gives up.
///
/// Four vowels of the `o`/`u` class already give 256 candidates, and a longer token is better
/// served by the compound path than by brute force.
const MAX_DIACRITIC_VOWELS: usize = 6;

/// Restores missing accents on an accent-stripped token.
///
/// Candidates are generated by `REP-DIAC-003` and ranked by `REP-DIAC-004`: an accepted analysis
/// first, then corpus frequency. `REP-DIAC-008` is why this abstains rather than guessing when two
/// readings are equally common: `orult` is both `őrült` and `örült`, and a repairer that picks one
/// silently corrupts the text it was asked to fix.
///
/// Rules: `REP-DIAC-003`, `REP-DIAC-004`, `REP-DIAC-008`
#[must_use]
pub fn restore_accents(word: &str) -> Option<String> {
    if starts_upper(word) && word.chars().skip(1).all(|c| !c.is_uppercase()) && !is_all_caps(word) {
        let lowered = lower_initial(word);
        return restore_accents(&lowered).map(|w| capitalise(&w));
    }
    let slots = candidates(word)?;
    let mut best: Vec<(u8, String)> = Vec::new();
    let mut buf = String::with_capacity(word.len() + slots.len());
    for n in 0..combinations(&slots) {
        fill(word, &slots, n, &mut buf);
        if buf != word && check(&buf) == Status::Ok {
            best.push((frequency(&buf), buf.clone()));
        }
    }
    ranked(best)
}

/// Whether any accent restoration of `word` is accepted.
///
/// `REP-DIAC-001` asks only whether a restoration exists, not which one is best, so this stops at
/// the first candidate the checker takes instead of ranking them all. On stripped Hungarian that
/// is usually the first or second of up to 4,096.
fn restores(word: &str) -> bool {
    candidates(word).is_some_and(|slots| {
        let mut buf = String::with_capacity(word.len() + slots.len());
        (0..combinations(&slots)).any(|n| {
            fill(word, &slots, n, &mut buf);
            buf != word && check(&buf) == Status::Ok
        })
    })
}

/// Letters from which an all-capital token is a word set in capitals rather than an acronym.
const MIN_CAPITAL_WORD_LETTERS: usize = 5;

/// Alphabetic tokens a segment needs before it can be classified (`REP-DIAC-001`).
const MIN_TOKENS: usize = 30;

/// Accented-letter share below which a Hungarian segment counts as stripped.
///
/// Measured: the lowest clean segment of 19,757 sits at 0.66% and the highest stripped one at
/// 0.00%, so the classes are separated and the cut is chosen for headroom.
const MAX_ACCENT_SHARE: f64 = 0.002;

/// Tokens rejected as written before the restoration clause is computed.
///
/// Without the floor a clean segment with one rejected token that happens to restore scores 1.0.
const MIN_REJECTED: usize = 5;

/// Rejected tokens actually restored to estimate the ratio.
///
/// The clause is a proportion, so a sample answers it as well as the whole, and restoration is the
/// expensive step: each token enumerates its accent assignments and asks the checker about every
/// one. Without the cap a paragraph of stripped Hungarian, which is the case the detector exists
/// for, costs as much as the rest of the document put together.
const RESTORE_SAMPLE: usize = 40;

/// Share of the rejected tokens that must become accepted after restoration.
const MIN_RESTORED: f64 = 0.5;

/// Whether `text` carries accents at all, at more than the share a stripped text can show.
///
/// The cheap half of [`is_accent_stripped`]: a text above the floor has its accents, so an
/// unaccented token in it is a token that lost one, not a text that never had any.
pub(crate) fn carries_accents(text: &str) -> bool {
    let letters = text.chars().filter(|c| c.is_alphabetic()).count().max(1);
    let accented = text.chars().filter(|c| ACCENTED.contains(*c)).count();
    #[expect(
        clippy::cast_precision_loss,
        reason = "counts are far below the f64 mantissa"
    )]
    let share = accented as f64 / letters as f64;
    share > MAX_ACCENT_SHARE
}

/// Whether `text` is Hungarian written without its accents (`REP-DIAC-001`).
///
/// Restoring accents is licensed by the segment, never by the token: `to`, `for` and `all` all
/// restore to real Hungarian words (`tó`, `fór`, `áll`), so a word-level restoration rewrites
/// English into Hungarian. The decisive clause is the last one, that most of the tokens rejected
/// as written become accepted after restoration; the function-word signature is only a pre-filter.
///
/// The detector abstains on anything shorter than a paragraph, which is what the rule asks for.
///
/// Rules: `REP-DIAC-001`
#[must_use]
pub fn is_accent_stripped(text: &str) -> bool {
    let words: Vec<&str> = tokens(text)
        .into_iter()
        .map(|(_, w)| w)
        .filter(|w| w.chars().any(char::is_alphabetic))
        .collect();
    if words.len() < MIN_TOKENS {
        return false;
    }
    let mut letters = 0usize;
    let mut accented = 0usize;
    for c in text.chars().filter(|c| c.is_alphabetic()) {
        letters += 1;
        if ACCENTED.contains(c) {
            accented += 1;
        }
    }
    #[expect(
        clippy::cast_precision_loss,
        reason = "counts are far below the f64 mantissa"
    )]
    let share = if letters == 0 {
        0.0
    } else {
        accented as f64 / letters as f64
    };
    if share >= MAX_ACCENT_SHARE {
        return false;
    }
    let mut seen: Vec<&str> = Vec::new();
    for w in &words {
        let lower = w.to_lowercase();
        if let Some(sig) = picur_morph_lexicon::words(Role::AccentSignature)
            .iter()
            .find(|s| s.as_ref() == lower)
            && !seen.contains(&sig.as_ref())
        {
            seen.push(sig);
        }
    }
    if seen.len() < 2 {
        return false;
    }
    let rejected: Vec<&&str> = words.iter().filter(|w| check(w) != Status::Ok).collect();
    if rejected.len() < MIN_REJECTED {
        return false;
    }
    // The clause is a proportion against a fixed threshold, so it is settled once either side passes
    // half the sample: foreign text fails it after about twenty tokens instead of forty.
    let sample = rejected.len().min(RESTORE_SAMPLE);
    #[expect(
        clippy::cast_precision_loss,
        clippy::cast_possible_truncation,
        clippy::cast_sign_loss,
        reason = "a count of sampled tokens"
    )]
    let need = (sample as f64 * MIN_RESTORED).ceil() as usize;
    let (mut yes, mut no) = (0usize, 0usize);
    for w in rejected.iter().take(sample) {
        if restores(w) {
            yes += 1;
        } else {
            no += 1;
        }
        if yes >= need || no > sample - need {
            break;
        }
    }
    yes >= need
}

/// The accent slots of `word`, or `None` when it has none or too many to enumerate.
fn candidates(word: &str) -> Option<Vec<(usize, &str)>> {
    if check(word) == Status::Ok || !word.chars().all(|c| c.is_lowercase() || !c.is_alphabetic()) {
        return None;
    }
    if is_guarded(word) || word.chars().any(char::is_numeric) {
        return None;
    }
    slots(word)
}

/// The positions of `word` an accent could have been lost at, with the letters it could be.
fn slots(word: &str) -> Option<Vec<(usize, &str)>> {
    let slots: Vec<(usize, &str)> = word
        .char_indices()
        .filter_map(|(i, c)| {
            DIACRITICS
                .iter()
                .find(|(base, _)| *base == c)
                .map(|(_, set)| (i, *set))
        })
        .collect();
    (!slots.is_empty() && slots.len() <= MAX_DIACRITIC_VOWELS).then_some(slots)
}

/// Restores the accents of an all-capital acronym the lexicon lists (`REP-DIAC-012`).
///
/// Accents are kept on capitals in Hungarian (`ORT-CAP-002`), so an all-capital segment without
/// them has lost them. An acronym is the one case the checker cannot help with, because it accepts
/// any all-capital token whatever its letters are (`ORT-ABBR-011`), so the evidence has to be the
/// lexicon's own listing: `MAV` becomes `MÁV` because `MÁV` is a listed acronym, and `USA` and
/// `NATO` stay because no accented reading of them is listed.
///
/// Rules: `REP-DIAC-012`, `ORT-ABBR-011`, `ORT-CAP-002`
pub(crate) fn restore_acronym(word: &str) -> Option<String> {
    if !is_all_caps(word)
        || !word.chars().all(char::is_alphabetic)
        || word.chars().any(|c| ACCENTED.contains(c))
    {
        return None;
    }
    let spelled = lower(word);
    // A short all-capital token is an acronym and is restored only to a listed one (`MÁV`); a
    // longer one is a word set in capitals (`ÁLTALÁNOS`) and is restored as the word.
    let is_word = letters(&spelled).count() >= MIN_CAPITAL_WORD_LETTERS;
    let slots = slots(&spelled)?;
    let mut found: Vec<(u8, String)> = Vec::new();
    let mut buf = String::with_capacity(spelled.len() + slots.len());
    for n in 0..combinations(&slots) {
        fill(&spelled, &slots, n, &mut buf);
        let candidate = upper(&buf);
        let listed = !lexicon().get(&candidate).is_empty() || (is_word && crate::vouched(&buf));
        if candidate != word && listed && !found.iter().any(|(_, c)| *c == candidate) {
            found.push((frequency(&buf), candidate));
        }
    }
    if is_word {
        return ranked(found);
    }
    match found.as_slice() {
        [(_, only)] => Some(only.clone()),
        _ => None,
    }
}

/// The commonest candidate, or nothing when the top two are equally attested (`REP-DIAC-004`,
/// `REP-DIAC-008`).
fn ranked(mut found: Vec<(u8, String)>) -> Option<String> {
    found.sort_by_key(|(n, _)| std::cmp::Reverse(*n));
    match found.as_slice() {
        [] => None,
        [(a, _), (b, _), ..] if a == b => None,
        [(_, first), ..] => Some(first.clone()),
    }
}

/// Every accent-only respelling of `word` the checker accepts, commonest first, `word` itself
/// included when it is accepted (`REP-DIAC-003`).
///
/// These are alternatives, not a repair: `kerek` is a word, and so are `kerék` and `kérek`, and
/// which was meant is a question for the context (`REP-DIAC-004`).
#[must_use]
pub fn accent_alternatives(word: &str) -> Vec<String> {
    let Some(slots) = slots(word).filter(|_| !is_guarded(word)) else {
        return Vec::new();
    };
    let mut found: Vec<(u8, String)> = Vec::new();
    let mut buf = String::with_capacity(word.len() + slots.len());
    for n in 0..combinations(&slots) {
        fill(word, &slots, n, &mut buf);
        if check(&buf) == Status::Ok && !found.iter().any(|(_, c)| *c == buf) {
            found.push((frequency(&buf), buf.clone()));
        }
    }
    found.sort_by_key(|(n, _)| std::cmp::Reverse(*n));
    found.into_iter().map(|(_, c)| c).collect()
}

/// Writes the `n`th accent assignment of `word` into `buf`.
fn fill(word: &str, slots: &[(usize, &str)], mut n: usize, buf: &mut String) {
    buf.clear();
    let mut prev = 0usize;
    for &(at, set) in slots {
        let k = set.chars().count();
        if let Some(pick) = set.chars().nth(n % k) {
            buf.push_str(&word[prev..at]);
            buf.push(pick);
        }
        n /= k;
        prev = at + 1;
    }
    buf.push_str(&word[prev..]);
}

/// How many accent assignments a slot list has.
fn combinations(slots: &[(usize, &str)]) -> usize {
    slots
        .iter()
        .map(|(_, set)| set.chars().count())
        .product::<usize>()
        .min(4096)
}

#[cfg(test)]
mod acronym_tests {
    use super::restore_acronym;

    /// `REP-DIAC-012`: the accented acronym has to be the listed one.
    #[test]
    fn rep_diac_012_a_listed_acronym_gets_its_accents() {
        assert_eq!(restore_acronym("MAV").as_deref(), Some("MÁV"));
    }

    /// Nothing else is restored: an unaccented acronym is not a damaged one.
    #[test]
    fn rep_diac_012_an_unlisted_reading_is_left_alone() {
        for word in ["USA", "NATO", "HTML", "MÁV", "Mav", "ART"] {
            assert_eq!(restore_acronym(word), None, "{word}");
        }
    }
}
